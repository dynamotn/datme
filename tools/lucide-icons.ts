/**
 * Writes src/lib/lucide-icons.ts: every icon of lucide-static (a dev
 * dependency) as the inside of its <svg>, in one module of about 0.5 MB.
 * Vaults pick any Lucide icon (Iconize, a base's icon property), so the whole
 * set ships, but not the 50 MB of fonts, sprites and JS that come with it.
 * Run `bun tools/lucide-icons.ts` after updating lucide-static; a test fails
 * while the module is out of date.
 */
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"

const root = path.resolve(import.meta.dir, "..")
export const target = path.join(root, "src/lib/lucide-icons.ts")

/** The text of src/lib/lucide-icons.ts, from the installed lucide-static. */
export function render(): string {
  const pkg = path.dirname(createRequire(import.meta.url).resolve("lucide-static/package.json"))
  const version = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8")).version as string
  const licence = fs.readFileSync(path.join(pkg, "LICENSE"), "utf8").trim()
  const dir = path.join(pkg, "icons")
  let open: string | undefined
  const lines: string[] = []
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".svg")) continue
    const svg = fs.readFileSync(path.join(dir, file), "utf8")
    const m = svg.match(/^<!--[\s\S]*?-->\s*(<svg\b[^>]*>)([\s\S]*)<\/svg>\s*$/)
    if (!m) throw new Error(`${file} is not a plain Lucide <svg>`)
    // The opening tag is the same for every icon but its class, which datme drops anyway.
    const tag = m[1].replace(/\sclass="[^"]*"/, "").replace(/\s+/g, " ")
    if (open !== undefined && tag !== open) throw new Error(`${file} opens its <svg> unlike the others: ${tag}`)
    open = tag
    lines.push(`  ${JSON.stringify(file.slice(0, -4))}: ${JSON.stringify(m[2].replace(/\s+/g, " ").trim())},`)
  }
  if (!open) throw new Error(`no icons in ${dir}`)
  return [
    `// Generated by tools/lucide-icons.ts from lucide-static ${version}: do not edit.`,
    "/*",
    ...licence.split("\n").map((l) => ` ${l}`.trimEnd()),
    "*/",
    "",
    "/** The opening tag of every Lucide icon. */",
    `export const LUCIDE_OPEN = ${JSON.stringify(open)}`,
    "",
    "/** The inside of each Lucide icon's <svg>, by its name. */",
    "export const LUCIDE: Record<string, string> = {",
    ...lines,
    "}",
    "",
  ].join("\n")
}

if (import.meta.main) {
  fs.writeFileSync(target, render())
  console.log(`wrote ${path.relative(root, target)} (${(fs.statSync(target).size / 1024).toFixed(0)} KiB)`)
}
